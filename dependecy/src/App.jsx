import { useState } from "react";
import Title from "./title.jsx";

function App() {
    const [count, setCount] = useState(0);
    const [form,setForm]=useState({
        firstName:"",email:"",age:""
    });
    const[isdisplay,setSubmit]=useState(false)
    const update=(e)=>{
        const{name,value}=e.target;
        setForm((perv)=>({...perv,[name]:value}))
    }
    
    
    const display=(e)=>{
        e.preventDefault();
        setSubmit(true);
    }
    return (
        <div>
            <Title count={count} />
            <button onClick={() => setCount(count + 1)}>
                Click me
            </button><br></br>

            <label>Name</label><br></br>
            <input name="firstName" value={form.firstName} onChange={update}></input><br></br>
            <label>Email</label><br></br>
            <input name="email" value={form.email} onChange={update}></input><br></br>
            <label>Age</label><br></br>
            <input name="age" value={form.age} onChange={update}></input><br></br>
            <button onClick={display}>Submit</button>
{/* {error && <p className="notice error">Could not load vehicles: {error}</p>} */}
            {isdisplay && (
                <>
          <h3>Submitted Details</h3>
          <label>Name: {form.Name}</label>
          <br />
          <label>Email: {form.email}</label>
          <br />
          <label>Age: {form.age}</label>
        </>
            )}

        </div>
    );
}

export default App;